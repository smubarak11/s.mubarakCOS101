              fn main() {
                // Using Vec::new()

             let v : Vec<i64> = Vec::new();

             // To find the length of the vector

             print!("The length of Vec::new() is {}", v.len());

             // Using a loaded vector (vector macro)

             let v =  vec!["Grace", "Effiong", "Kareem", "Susan", "Basil"];

             // Finding the length of the macro

             println!("\nThe length of the macro v! is {}", v.len());

                       
}
